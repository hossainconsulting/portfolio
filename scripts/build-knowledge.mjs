// Builds src/knowledge.js, the CONCIERGE widget's knowledge base, from the public pages
// in public/. The assistant answers visitors' questions about Hemayet's work from this
// text and nothing else, so it has to say exactly what the site says. Regenerate it
// whenever a source page changes:
//
//   node scripts/build-knowledge.mjs          # rewrite src/knowledge.js
//   node scripts/build-knowledge.mjs --check  # fail if src/knowledge.js is stale (npm run check)
//
// No dependencies: the pages are hand-written HTML, so tag stripping is enough.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import path from "node:path";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "src", "knowledge.js");

// Pages the assistant may answer from, with the public URL it should point visitors to.
const SOURCES = [
  { file: "public/index.html", url: "https://portfolio.hossainconsulting.com/" },
  { file: "public/service-agent-patterns.html", url: "https://portfolio.hossainconsulting.com/service-agent-patterns" },
  { file: "public/writing/claude-with-microsoft-365.html", url: "https://portfolio.hossainconsulting.com/writing/claude-with-microsoft-365" },
];

const ENTITIES = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", times: "×", middot: "·", mdash: "—", ndash: "–", rsquo: "’", lsquo: "‘", rdquo: "”", ldquo: "“", hellip: "…", rarr: "→", larr: "←" };
function decode(s) {
  return s
    .replace(/&#x([0-9a-f]+);/gi, (_, h) => String.fromCodePoint(parseInt(h, 16)))
    .replace(/&#(\d+);/g, (_, d) => String.fromCodePoint(Number(d)))
    .replace(/&([a-z]+);/gi, (m, n) => ENTITIES[n.toLowerCase()] ?? m);
}

export function htmlToText(html, baseUrl) {
  let body = html;
  const start = body.search(/<body[\s>]/i);
  if (start >= 0) body = body.slice(start);
  // Stop after the footer: the chat widget markup and scripts come after it.
  const footerEnd = body.search(/<\/footer>/i);
  if (footerEnd >= 0) body = body.slice(0, footerEnd + "</footer>".length);

  body = body
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<(script|style|noscript|svg|template)[\s\S]*?<\/\1>/gi, "")
    // Keep link targets so the assistant can point visitors at the right page.
    .replace(/<a\b[^>]*href="([^"#][^"]*)"[^>]*>([\s\S]*?)<\/a>/gi, (_, href, text) => {
      const label = text.replace(/<[^>]+>/g, "").trim();
      if (/^mailto:/i.test(href)) return label;
      let abs;
      try { abs = new URL(decode(href), baseUrl).href; } catch { return label; }
      return label ? `${label} (${abs})` : abs;
    })
    // Source line wraps are layout, not meaning: join them so sentences stay whole.
    .replace(/\s+/g, " ")
    .replace(/<(br|hr)\b[^>]*>/gi, "\n")
    .replace(/<\/(td|th)>/gi, " | ")
    .replace(/<\/?(p|div|section|article|header|footer|main|nav|li|ul|ol|h[1-6]|tr|table|blockquote|figure|figcaption|dl|dt|dd)\b[^>]*>/gi, "\n")
    .replace(/<[^>]+>/g, "");

  return decode(body)
    .split("\n")
    .map((l) => l.replace(/[ \t]+/g, " ").replace(/\s*\|\s*$/, "").trim())
    .filter(Boolean)
    .join("\n");
}

async function build() {
  const parts = [];
  for (const s of SOURCES) {
    const html = await readFile(path.join(root, s.file), "utf8");
    parts.push(`<page url="${s.url}" source="${s.file}">\n${htmlToText(html, s.url)}\n</page>`);
  }
  const text = parts.join("\n\n");
  const hash = createHash("sha256").update(text).digest("hex").slice(0, 16);
  return (
    "// GENERATED by scripts/build-knowledge.mjs from the public pages listed there.\n" +
    "// Do not edit by hand: change the page, then run `node scripts/build-knowledge.mjs`.\n\n" +
    `export const KNOWLEDGE_HASH = ${JSON.stringify(hash)};\n\n` +
    `export const KNOWLEDGE = ${JSON.stringify(text)};\n`
  );
}

const next = await build();
if (process.argv.includes("--check")) {
  const current = await readFile(OUT, "utf8").catch(() => "");
  if (current !== next) {
    console.error("src/knowledge.js is stale: run `node scripts/build-knowledge.mjs` and commit the result.");
    process.exit(1);
  }
  console.log("knowledge: src/knowledge.js matches the public pages.");
} else {
  await writeFile(OUT, next);
  console.log(`knowledge: wrote src/knowledge.js (${next.length} chars).`);
}
